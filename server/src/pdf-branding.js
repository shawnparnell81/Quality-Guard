/* ============================================================
   Shared PDF letterhead.

   Every PDF this app generates - a single record, a management
   scorecard, whatever comes next - opens with the same mark and
   closes with the same footer, so pulled apart from records.js
   where it started rather than redrawn per document.
   ============================================================ */

export const BRAND = "#0D4F49";
export const BRASS = "#A8703A";
export const INK = "#12201E";
export const INK_2 = "#4C5C59";
export const HAIRLINE = "#D8E1DF";

export function humanizeKey(key) {
    return key.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

/* The same mountain-and-baseline mark used in the app's own header,
   redrawn in pdfkit's vector primitives rather than embedded as an
   image - the whole mark is four strokes and a dot. */
export function drawLetterhead(doc, orgName, subtitle) {
    const x = doc.page.margins.left;
    const y = doc.y;
    const size = 26;

    doc.roundedRect(x, y, size, size, 5).lineWidth(1.3).stroke(BRAND);
    doc.moveTo(x + 6, y + 19).lineTo(x + 13, y + 6).lineTo(x + 20, y + 19)
        .lineWidth(1.6).stroke(INK);
    doc.moveTo(x + 5, y + 19).lineTo(x + 21, y + 19).lineWidth(1.6).stroke(BRASS);
    doc.circle(x + 13, y + 19, 1.8).fill(BRASS);

    doc.fontSize(14).fillColor(INK).font("Helvetica-Bold")
        .text("QualityGuard", x + size + 10, y + 1);
    doc.fontSize(8.5).fillColor(INK_2).font("Helvetica")
        .text(subtitle || orgName, x + size + 10, y + 17);

    doc.y = y + size + 12;
    doc.moveTo(x, doc.y).lineTo(doc.page.width - doc.page.margins.right, doc.y)
        .lineWidth(0.75).stroke(HAIRLINE);
    doc.moveDown(1.2);
}

/* The footer sits 12pt below the bottom margin on purpose - in the
   page's true footer zone, not the printable body. pdfkit's own
   wrap() checks the given y against page.maxY() (height - margins.
   bottom) before it draws a single character, on every text() call
   with no exception for an intentionally-placed one: a y past that
   line reads as an overflow and silently starts a new page instead
   of drawing - so every record's PDF has been carrying one spurious
   trailing blank page for as long as this function has existed.
   Lowering the margin to 0 only for this call raises maxY to the
   full page height, so the same y this always used now falls inside
   it and pdfkit draws instead of paginating. */
export function drawFooter(doc, orgName) {
    const bottomMargin = doc.page.margins.bottom;
    doc.page.margins.bottom = 0;

    doc.fontSize(7.5).fillColor(INK_2).text(
        "Generated by QualityGuard for " + orgName + " on " + new Date().toLocaleString(),
        doc.page.margins.left,
        doc.page.height - bottomMargin + 12,
        { width: doc.page.width - doc.page.margins.left - doc.page.margins.right, align: "center" }
    );

    doc.page.margins.bottom = bottomMargin;
}
